def to_json(ctx: dict, report_type: str) -> str:
    return json.dumps({
        "type": report_type,
        "title": REPORT_TYPES.get(report_type, report_type),
        "project": ctx["project"].get("name"),
        "generated_at": _now(),
        "data": {
            "pages": ctx["pages"],
            "features": ctx["features"],
            "evidence": ctx["evidence"],
            "observations": ctx["observations"],
            "analytics": ctx["analytics"],
        },
    }, indent=2, default=str)


def to_csv(ctx: dict, report_type: str) -> str:
    buf = io.StringIO()
    w = csv.writer(buf)
    if report_type == "evidence_register":
        w.writerow(["id", "class", "source", "description", "capture_method", "captured_at"])
        for e in ctx["evidence"]:
            w.writerow([e.get("ref_code") or e["id"], e["evidence_class"], e.get("source_name") or e.get("source_uri"),
                        e.get("description"), e.get("capture_method"), e.get("captured_at")])
    elif report_type == "feature_inventory":
        w.writerow(["name", "category", "description", "purpose", "access_location", "inputs", "outputs",
                    "observed_behaviour", "dependencies", "related_features", "user_journey", "limitations",
                    "opportunities", "implementation_implications", "evidence_ids", "confidence", "status"])
        for f in ctx["features"]:
            w.writerow([f.get("name"), f.get("category"), f.get("description"), f.get("purpose"),
                        f.get("access_location"), f.get("inputs"), f.get("outputs"), f.get("observed_behaviour"),
                        "; ".join(f.get("dependencies") or []), "; ".join(f.get("related_features") or []),
                        f.get("user_journey"), f.get("limitations"), f.get("opportunities"),
                        f.get("implementation_implications"), "; ".join(f.get("evidence_ids") or []),
                        f.get("confidence"), f.get("status")])
    elif report_type == "page_audit":
        w.writerow(["url", "title", "status", "content_category", "purpose", "capture_method", "observed_at", "error"])
        for pg in ctx["pages"]:
            w.writerow([pg.get("url"), pg.get("title"), pg["status"], pg.get("content_category"),
                        pg.get("purpose"), pg.get("capture_method"), pg.get("observed_at"), pg.get("error")])
    else:
        w.writerow(["type", "note"])
        w.writerow([report_type, "CSV export available for: evidence_register, feature_inventory, page_audit"])
    return buf.getvalue()


