def gen_prd(ctx: dict) -> str:
    p = ctx["project"]
    lines = [
        f"# Product Requirement Document (research-derived) — {p['name']}",
        "",
        f"Generated: {_now()} · Status: **DRAFT — requires product-team review**",
        "",
        "This PRD is derived *only* from documented findings and recorded decisions. "
        "Anything not evidenced is marked as an assumption to be verified.",
        "",
        "## 1. Research basis",
        "",
        f"- Project: {p['name']} — {p.get('description') or ''}",
        f"- Pages documented: {sum(1 for x in ctx['pages'] if x['status'] == 'documented')}/{len(ctx['pages'])}",
        f"- Features documented: {len(ctx['features'])}",
        f"- Open questions: {ctx['analytics']['missing_information']['open_questions']}",
        "",
        "## 2. Requirements derived from gaps and opportunities",
        "",
    ]
    for i, o in enumerate(ctx["analytics"]["gaps_and_opportunities"]["opportunities"][:25], 1):
        lines.append(f"{i}. **{o['feature']}** (category: {o['category']}, opportunity {o['score']:.2f}) — {o['opportunity_note'] or 'see Analytics for component breakdown'}")
    lines += ["", "## 3. Assumptions flagged for verification", ""]
    hyp = [o for o in ctx["observations"] if o.get("evidence_class") == "H"][:20]
    lines += [f"- {o['observation'][:240]}" for o in hyp] or ["_None._"]
    lines += ["", _evidence_footer(ctx["evidence"], p["name"])]
    return "\n".join(lines)


def gen_roadmap(ctx: dict) -> str:
    p = ctx["project"]
    lines = [f"# Development Roadmap (research-informed) — {p['name']}", "", f"Generated: {_now()}", "",
             "Sequencing heuristic: verified evidence first, high-opportunity gaps next, "
             "low-confidence (S/H) items after manual verification.", ""]
    a = ctx["analytics"]
    lines.append("## Phase 1 — Foundations (high evidence, verified)")
    lines.append("")
    hi = [o for o in a["gaps_and_opportunities"]["opportunities"] if o["components"]["evidence_weakness"] < 0.3][:10]
    lines += [f"- {o['feature']} — {o['opportunity_note'][:140] or 'close documented gap'}" for o in hi] or ["- (none scored with strong evidence yet)"]
    lines.append("")
    lines.append("## Phase 2 — Differentiators (opportunity-scored)")
    lines.append("")
    mid = [o for o in a["gaps_and_opportunities"]["opportunities"] if o["score"] >= 0.5][:12]
    lines += [f"- {o['feature']} (score {o['score']:.2f})" for o in mid] or ["- (none yet)"]
    lines.append("")
    lines.append("## Phase 3 — Verify-then-build (secondary evidence only)")
    lines.append("")
    low = [o for o in a["gaps_and_opportunities"]["opportunities"] if o["components"]["evidence_weakness"] >= 0.45][:12]
    lines += [f"- {o['feature']} — needs primary evidence before build" for o in low] or ["- (none yet)"]
    lines += ["", "## Open questions gating roadmap items", ""]
    qs = [q for q in ctx["questions"] if q.get("status") == "open"]
    lines += [f"- {q['question'][:220]}" for q in qs[:15]] or ["_None._"]
    lines += ["", _evidence_footer(ctx["evidence"], p["name"])]
    return "\n".join(lines)


def gen_evidence_register(ctx: dict) -> str:
    p = ctx["project"]
    lines = [f"# Evidence Register — {p['name']}", "", f"Generated: {_now()}", "",
             "Class: **C**=first-party confirmed · **I**=inference · **S**=secondary · **H**=hypothesis · **U**=unknown", ""]
    rows = []
    for e in sorted(ctx["evidence"], key=lambda x: (x.get("ref_code") or x["id"])):
        cited = e.get("cited_by") or []
        rows.append([e.get("ref_code") or e["id"], e["evidence_class"],
                     e.get("source_name") or e.get("source_uri") or "—",
                     (e.get("description") or "")[:220], e.get("capture_method") or "—",
                     e.get("captured_at") or "", str(len(cited))])
    lines.append(_md_table(["ID", "Class", "Source", "Key observations", "Capture", "Captured", "Cited by"], rows[:300]))
    lines += ["", f"Total evidence items: {len(ctx['evidence'])}", ""]
    return "\n".join(lines)


