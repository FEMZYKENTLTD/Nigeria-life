def _now() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")


def _evidence_footer(evidence: list[dict], project_name: str) -> str:
    cited = sorted({eid for e in evidence for eid in (e.get("cited_by") or [])})
    lines = [
        "---",
        "*Generated by the Nigeria Life Intelligence Engine.*",
        f"Generated: {_now()} · Project: **{project_name}**",
        "",
        "## Evidence referenced in this report",
    ]
    if evidence:
        lines.append("| Code | Class | Source | Capture |")
        lines.append("| --- | --- | --- | --- |")
        for e in evidence[:60]:
            code = e.get("ref_code") or e["id"]
            lines.append(f"| {code} | {e['evidence_class']} | {e.get('source_name') or e.get('source_uri') or '—'} | {e.get('capture_method') or '—'} |")
    else:
        lines.append("_No evidence records are linked to this report yet._")
    if cited:
        lines.append("")
        lines.append(f"Finding IDs citing evidence in this report: {', '.join(cited[:40])}")
    return "\n".join(lines)


def _md_table(headers: list[str], rows: list[list]) -> str:
    out = ["| " + " | ".join(h.replace("|", "/") for h in headers) + " |",
           "| " + " | ".join(["---"] * len(headers)) + " |"]
    for r in rows:
        cells = []
        for c in r:
            c = "" if c is None else str(c)
            c = c.replace("\n", " ⏎ ").replace("|", "\\|")
            cells.append(c[:300])
        out.append("| " + " | ".join(cells) + " |")
    return "\n".join(out)


def _rows_as_dicts(items: list[dict], fields: list[str]) -> list[dict]:
    return [{f: it.get(f, "") for f in fields} for it in items]


