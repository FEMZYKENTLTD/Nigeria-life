def render_report(report_type: str, ctx: dict, fmt: str) -> str:
    if report_type not in GENERATORS:
        raise ValueError(f"Unknown report type: {report_type}")
    if fmt == "json":
        return to_json(ctx, report_type)
    if fmt == "csv":
        return to_csv(ctx, report_type)
    md = GENERATORS[report_type](ctx)
    if fmt == "md" or fmt == "mermaid":
        return md
    if fmt == "html":
        return to_html(md, REPORT_TYPES[report_type])
    raise ValueError(f"Unknown format: {fmt}")
