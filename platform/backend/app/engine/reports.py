"""Report generation.

Fourteen report types in Markdown, JSON, CSV, HTML and Mermaid. Every
generated document carries an evidence-reference footer and the
investigation date, per the directive. Markdown is the source of truth;
HTML is a self-contained rendered form (usable for PDF via print); CSV is a
flat export of the underlying rows.
"""
